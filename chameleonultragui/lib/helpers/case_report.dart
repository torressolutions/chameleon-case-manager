import 'package:chameleonultragui/helpers/general.dart';
import 'package:chameleonultragui/sharedprefsprovider.dart';

/// Builds a human-readable Markdown report for a single captured card, suitable
/// for a pentest engagement write-up. Pure (no I/O) so it can be unit-tested and
/// reused both on disk (report.md) and inside an exported case zip.
String caseReportMarkdown(CardSave card) {
  final b = StringBuffer();
  b.writeln('# Card: ${card.name}');
  b.writeln();
  b.writeln('- **UID:** `${card.uid}`');
  b.writeln('- **Type:** ${card.tag.name}');
  b.writeln('- **SAK:** '
      '`${card.sak.toRadixString(16).padLeft(2, '0').toUpperCase()}`');
  if (card.atqa.isNotEmpty) {
    b.writeln('- **ATQA:** `${bytesToHexSpace(card.atqa)}`');
  }
  if (card.ats.isNotEmpty) {
    b.writeln('- **ATS:** `${bytesToHexSpace(card.ats)}`');
  }
  if (card.capturedAt != null) {
    b.writeln('- **Captured:** ${card.capturedAt}');
  }
  if (card.capturedBy != null) {
    b.writeln('- **Captured by:** ${card.capturedBy}');
  }
  b.writeln();

  final eng = card.engagement;
  if (eng != null && !eng.isEmpty) {
    b.writeln('## Engagement');
    b.writeln();
    if (eng.client != null && eng.client!.isNotEmpty) {
      b.writeln('- **Client:** ${eng.client}');
    }
    if (eng.scopeRef != null && eng.scopeRef!.isNotEmpty) {
      b.writeln('- **Scope / authorization ref:** ${eng.scopeRef}');
    }
    if (eng.authorizedBy != null && eng.authorizedBy!.isNotEmpty) {
      b.writeln('- **Authorized by:** ${eng.authorizedBy}');
    }
    if (eng.notes != null && eng.notes!.isNotEmpty) {
      b.writeln('- **Notes:** ${eng.notes}');
    }
    b.writeln();
  }

  final loc = card.location;
  if (loc != null) {
    b.writeln('## Location');
    b.writeln();
    b.writeln('- **Coordinates:** ${loc.latitude}, ${loc.longitude}');
    if (loc.accuracy != null) {
      b.writeln('- **Accuracy:** ±${loc.accuracy!.toStringAsFixed(1)} m');
    }
    if (loc.timestamp != null) {
      b.writeln('- **Fix time:** ${loc.timestamp}');
    }
    b.writeln('- **Map:** '
        '[OpenStreetMap](https://www.openstreetmap.org/?mlat='
        '${loc.latitude}&mlon=${loc.longitude}#map=18/'
        '${loc.latitude}/${loc.longitude})');
    b.writeln();
  }

  if (card.media.isNotEmpty) {
    b.writeln('## Photos');
    b.writeln();
    for (final m in card.media) {
      final caption = (m.caption != null && m.caption!.isNotEmpty)
          ? m.caption!
          : m.filename;
      b.writeln('![$caption](${m.filename})');
      b.writeln();
    }
  }

  if (card.data.isNotEmpty) {
    b.writeln('## Dump');
    b.writeln();
    b.writeln('```');
    for (int i = 0; i < card.data.length; i++) {
      b.writeln('${i.toString().padLeft(3)}: ${bytesToHexSpace(card.data[i])}');
    }
    b.writeln('```');
    b.writeln();
  }

  b.writeln('---');
  b.writeln('_Generated by Chameleon Case Manager for authorized security '
      'testing._');
  return b.toString();
}
